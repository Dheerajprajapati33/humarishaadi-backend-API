const mongoose = require("mongoose");
const profileSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      unique: true,
      index: true,
    },
    profileFor: String,
    gender: { type: String, enum: ["male", "female", "other"] },
    name: String,
    dob: Date,
    religion: String,
    caste: String,
    otherCastes: Boolean,
    gotra: String,
    motherTongue: [String],
    city: {
      name: String,
      state: String,
      stateCode: String,
      districtCode: String,
    },
    height: String,
    diet: String,
    maritalStatus: String,
    about: String,
    photos: [{ url: String, publicId: String, isPrimary: Boolean }],
    occupation: String,
    salaryRange: String,
    companyName: String,
    companyLocation: String,
    education: String,
    family: {
      fatherStatus: String,
      motherStatus: String,
      place: String,
      monthlySalary: String,
      property: [String],
      type: { type: String },
      siblings: String,
    },
    astrology: { mangalDosha: String, birthPlace: String, birthTime: String },
    health: {
      alcohol: String,
      smoking: String,
      issues: [String],
      disability: String,
    },
    verification: {
      status: {
        type: String,
        enum: ["not_submitted", "pending", "verified", "rejected"],
        default: "not_submitted",
      },
      documentUrl: String,
      remarks: String,
    },
    completion: { type: Number, default: 0 },
  },
  { timestamps: true },
);
module.exports = mongoose.model("Profile", profileSchema);
